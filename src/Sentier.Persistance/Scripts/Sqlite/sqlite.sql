-- Sentier : schéma SQLite (tables, compteurs de séquences, index, vue).
-- Le jeton {{P}} est remplacé par le préfixe configuré (OptionsSentier.PrefixeTables).
-- Les séquences Oracle sont émulées par la table {{P}}_SEQ, incrémentée dans la transaction.
-- Les noms d'objets suivent les mnémoniques de BpmPlus.

CREATE TABLE IF NOT EXISTS {{P}}_SEQ (
    NOM_SEQ             TEXT NOT NULL PRIMARY KEY,
    VAL_SEQ             INTEGER NOT NULL
);

INSERT OR IGNORE INTO {{P}}_SEQ (NOM_SEQ, VAL_SEQ) VALUES ('{{P}}_SEQ_DEFIN', 0);
INSERT OR IGNORE INTO {{P}}_SEQ (NOM_SEQ, VAL_SEQ) VALUES ('{{P}}_SEQ_INSTC', 0);
INSERT OR IGNORE INTO {{P}}_SEQ (NOM_SEQ, VAL_SEQ) VALUES ('{{P}}_SEQ_HIST_NOEUD', 0);
INSERT OR IGNORE INTO {{P}}_SEQ (NOM_SEQ, VAL_SEQ) VALUES ('{{P}}_SEQ_ATTEN', 0);
INSERT OR IGNORE INTO {{P}}_SEQ (NOM_SEQ, VAL_SEQ) VALUES ('{{P}}_SEQ_MIGRA', 0);

CREATE TABLE IF NOT EXISTS {{P}}_DEFIN_PROCS (
    NO_SEQ_DEFIN_PROCS  INTEGER NOT NULL,
    CLE                 TEXT NOT NULL,
    VERSI               INTEGER NOT NULL,
    NOM_DEFIN           TEXT NOT NULL,
    IND_INSTC_UNIQ      INTEGER NOT NULL,
    IND_MIGRA_AUTO      INTEGER NOT NULL,
    DEFIN_JSON          TEXT NOT NULL,
    EMPRE               TEXT NOT NULL,
    IND_ACTIV           INTEGER NOT NULL,
    DH_CREA             TEXT NOT NULL,
    PRIMARY KEY (NO_SEQ_DEFIN_PROCS)
);

CREATE UNIQUE INDEX IF NOT EXISTS UQ_{{P}}_DEFIN_CLE_VER ON {{P}}_DEFIN_PROCS (CLE, VERSI);
CREATE INDEX IF NOT EXISTS IDX_{{P}}_DEFIN_ACTIV ON {{P}}_DEFIN_PROCS (CLE, IND_ACTIV);

CREATE TABLE IF NOT EXISTS {{P}}_INSTC_PROCS (
    NO_SEQ_INSTC_PROCS  INTEGER NOT NULL,
    NO_SEQ_DEFIN_PROCS  INTEGER NOT NULL,
    CLE_DEFIN           TEXT NOT NULL,
    ID_INSTC_PARN       INTEGER,
    ID_NOEUD_PARN       TEXT,
    AGGRE_ID            INTEGER NOT NULL,
    IND_INSTC_UNIQ      INTEGER NOT NULL,
    STAT                TEXT NOT NULL,
    ID_NOEUD_FIN        TEXT,
    ID_NOEUD_COUR       TEXT NOT NULL,
    ID_TACH_EXTE        INTEGER,
    VAR_JSON            TEXT,
    MESS_ERR            TEXT,
    DH_ERR              TEXT,
    VERSI               INTEGER NOT NULL,
    DH_CREA             TEXT NOT NULL,
    DH_MODIF            TEXT NOT NULL,
    DH_FIN              TEXT,
    PRIMARY KEY (NO_SEQ_INSTC_PROCS),
    CONSTRAINT FK_{{P}}_INSTC_DEFIN FOREIGN KEY (NO_SEQ_DEFIN_PROCS) REFERENCES {{P}}_DEFIN_PROCS (NO_SEQ_DEFIN_PROCS),
    CONSTRAINT FK_{{P}}_INSTC_PARN FOREIGN KEY (ID_INSTC_PARN) REFERENCES {{P}}_INSTC_PROCS (NO_SEQ_INSTC_PROCS)
);

-- Une seule instance active par processus et par clé d'affaire (instances à instance unique) : index unique partiel.
CREATE UNIQUE INDEX IF NOT EXISTS UQ_{{P}}_INSTC_UNIQ ON {{P}}_INSTC_PROCS (AGGRE_ID, CLE_DEFIN)
    WHERE IND_INSTC_UNIQ = 1 AND STAT IN ('EN_COURS', 'SUSPENDUE', 'EN_ERREUR');
CREATE INDEX IF NOT EXISTS IDX_{{P}}_INSTC_STAT ON {{P}}_INSTC_PROCS (STAT);
CREATE INDEX IF NOT EXISTS IDX_{{P}}_INSTC_NOEUD ON {{P}}_INSTC_PROCS (NO_SEQ_DEFIN_PROCS, ID_NOEUD_COUR);
CREATE INDEX IF NOT EXISTS IDX_{{P}}_INSTC_AGGID ON {{P}}_INSTC_PROCS (AGGRE_ID, CLE_DEFIN);
CREATE INDEX IF NOT EXISTS IDX_{{P}}_INSTC_PARN ON {{P}}_INSTC_PROCS (ID_INSTC_PARN);

CREATE TABLE IF NOT EXISTS {{P}}_HIST_NOEUD_PROCS (
    NO_SEQ_HIST_NOEUD_PROCS INTEGER NOT NULL,
    NO_SEQ_INSTC_PROCS      INTEGER NOT NULL,
    ID_NOEUD                TEXT NOT NULL,
    TYP_NOEUD               TEXT NOT NULL,
    DH_ENTRE                TEXT NOT NULL,
    DH_SORTI                TEXT,
    RESUL                   TEXT,
    PRIMARY KEY (NO_SEQ_HIST_NOEUD_PROCS),
    CONSTRAINT FK_{{P}}_HIST_INSTC FOREIGN KEY (NO_SEQ_INSTC_PROCS) REFERENCES {{P}}_INSTC_PROCS (NO_SEQ_INSTC_PROCS)
);

CREATE INDEX IF NOT EXISTS IDX_{{P}}_HIST_INSTC ON {{P}}_HIST_NOEUD_PROCS (NO_SEQ_INSTC_PROCS);

CREATE TABLE IF NOT EXISTS {{P}}_ATTEN_PROCS (
    NO_SEQ_ATTEN_PROCS  INTEGER NOT NULL,
    NO_SEQ_INSTC_PROCS  INTEGER NOT NULL,
    ID_NOEUD            TEXT NOT NULL,
    TYP_DECLN           TEXT NOT NULL,
    NOM_SORTI           TEXT NOT NULL,
    DH_ECHEA            TEXT,
    NOM_SIGNL           TEXT,
    CLE_CORRL           TEXT,
    DH_CREA             TEXT NOT NULL,
    PRIMARY KEY (NO_SEQ_ATTEN_PROCS),
    CONSTRAINT FK_{{P}}_ATTEN_INSTC FOREIGN KEY (NO_SEQ_INSTC_PROCS) REFERENCES {{P}}_INSTC_PROCS (NO_SEQ_INSTC_PROCS)
);

CREATE INDEX IF NOT EXISTS IDX_{{P}}_ATTEN_ECHEA ON {{P}}_ATTEN_PROCS (TYP_DECLN, DH_ECHEA);
CREATE INDEX IF NOT EXISTS IDX_{{P}}_ATTEN_SIGNL ON {{P}}_ATTEN_PROCS (NOM_SIGNL, CLE_CORRL);
CREATE INDEX IF NOT EXISTS IDX_{{P}}_ATTEN_INSTC ON {{P}}_ATTEN_PROCS (NO_SEQ_INSTC_PROCS, ID_NOEUD);

CREATE TABLE IF NOT EXISTS {{P}}_MIGRA_PROCS (
    NO_SEQ_MIGRA_PROCS  INTEGER NOT NULL,
    NO_SEQ_INSTC_PROCS  INTEGER NOT NULL,
    NO_SEQ_DEFIN_SOURC  INTEGER NOT NULL,
    NO_SEQ_DEFIN_CIBLE  INTEGER NOT NULL,
    MODE_MIGRA          TEXT NOT NULL,
    DETL                TEXT,
    LOGON_UTIL          TEXT,
    DH_MIGRA            TEXT NOT NULL,
    PRIMARY KEY (NO_SEQ_MIGRA_PROCS),
    CONSTRAINT FK_{{P}}_MIGRA_INSTC FOREIGN KEY (NO_SEQ_INSTC_PROCS) REFERENCES {{P}}_INSTC_PROCS (NO_SEQ_INSTC_PROCS),
    CONSTRAINT FK_{{P}}_MIGRA_SOURC FOREIGN KEY (NO_SEQ_DEFIN_SOURC) REFERENCES {{P}}_DEFIN_PROCS (NO_SEQ_DEFIN_PROCS),
    CONSTRAINT FK_{{P}}_MIGRA_CIBLE FOREIGN KEY (NO_SEQ_DEFIN_CIBLE) REFERENCES {{P}}_DEFIN_PROCS (NO_SEQ_DEFIN_PROCS)
);

CREATE INDEX IF NOT EXISTS IDX_{{P}}_MIGRA_INSTC ON {{P}}_MIGRA_PROCS (NO_SEQ_INSTC_PROCS);

-- Instances actives avec la clé et la version de leur définition, pour les requêtes SQL ad hoc.
CREATE VIEW IF NOT EXISTS {{P}}_V_INSTC_ACTIV AS
SELECT i.NO_SEQ_INSTC_PROCS, i.CLE_DEFIN, d.VERSI AS VERSI_DEFIN, i.NO_SEQ_DEFIN_PROCS, i.AGGRE_ID, i.STAT,
       i.ID_NOEUD_COUR, i.ID_TACH_EXTE, i.ID_INSTC_PARN, i.MESS_ERR, i.DH_CREA, i.DH_MODIF
FROM {{P}}_INSTC_PROCS i
JOIN {{P}}_DEFIN_PROCS d ON d.NO_SEQ_DEFIN_PROCS = i.NO_SEQ_DEFIN_PROCS
WHERE i.STAT IN ('EN_COURS', 'SUSPENDUE', 'EN_ERREUR');
