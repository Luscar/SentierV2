-- Sentier : schéma SQLite (tables, compteurs de séquences, index, vue).
-- Le jeton {{P}} est remplacé par le préfixe configuré (OptionsSentier.PrefixeTables).
-- Les séquences Oracle sont émulées par la table {{P}}_SEQUENCE, incrémentée dans la transaction.

CREATE TABLE IF NOT EXISTS {{P}}_SEQUENCE (
    NOM                 TEXT NOT NULL PRIMARY KEY,
    VALEUR              INTEGER NOT NULL
);

INSERT OR IGNORE INTO {{P}}_SEQUENCE (NOM, VALEUR) VALUES ('{{P}}_SEQ_DEFINITION', 0);
INSERT OR IGNORE INTO {{P}}_SEQUENCE (NOM, VALEUR) VALUES ('{{P}}_SEQ_INSTANCE', 0);
INSERT OR IGNORE INTO {{P}}_SEQUENCE (NOM, VALEUR) VALUES ('{{P}}_SEQ_HIST_NOEUD', 0);
INSERT OR IGNORE INTO {{P}}_SEQUENCE (NOM, VALEUR) VALUES ('{{P}}_SEQ_ATTENTE', 0);
INSERT OR IGNORE INTO {{P}}_SEQUENCE (NOM, VALEUR) VALUES ('{{P}}_SEQ_TACHE', 0);
INSERT OR IGNORE INTO {{P}}_SEQUENCE (NOM, VALEUR) VALUES ('{{P}}_SEQ_MIGRATION', 0);

CREATE TABLE IF NOT EXISTS {{P}}_DEFINITION (
    ID                  INTEGER NOT NULL,
    CLE_PROCESSUS       TEXT NOT NULL,
    VERSION             INTEGER NOT NULL,
    NOM                 TEXT NOT NULL,
    INSTANCE_UNIQUE     INTEGER NOT NULL,
    MIGRATION_AUTO      INTEGER NOT NULL,
    CONTENU             TEXT NOT NULL,
    EMPREINTE           TEXT NOT NULL,
    EST_ACTIVE          INTEGER NOT NULL,
    DATE_CREATION       TEXT NOT NULL,
    PRIMARY KEY (ID)
);

CREATE UNIQUE INDEX IF NOT EXISTS {{P}}_UX_DEF_VERSION ON {{P}}_DEFINITION (CLE_PROCESSUS, VERSION);
CREATE INDEX IF NOT EXISTS {{P}}_IX_DEF_ACTIVE ON {{P}}_DEFINITION (CLE_PROCESSUS, EST_ACTIVE);

CREATE TABLE IF NOT EXISTS {{P}}_INSTANCE (
    ID                  INTEGER NOT NULL,
    ID_DEFINITION       INTEGER NOT NULL,
    CLE_PROCESSUS       TEXT NOT NULL,
    ID_INSTANCE_PARENT  INTEGER,
    CODE_NOEUD_PARENT   TEXT,
    CLE_AFFAIRE         INTEGER NOT NULL,
    INSTANCE_UNIQUE     INTEGER NOT NULL,
    STATUT              TEXT NOT NULL,
    CODE_FIN            TEXT,
    CODE_NOEUD_COURANT  TEXT NOT NULL,
    VARIABLES           TEXT,
    MESSAGE_ERREUR      TEXT,
    DATE_ERREUR         TEXT,
    VERSION             INTEGER NOT NULL,
    DATE_CREATION       TEXT NOT NULL,
    DATE_MAJ            TEXT NOT NULL,
    DATE_FIN            TEXT,
    PRIMARY KEY (ID),
    CONSTRAINT {{P}}_FK_INST_DEF FOREIGN KEY (ID_DEFINITION) REFERENCES {{P}}_DEFINITION (ID),
    CONSTRAINT {{P}}_FK_INST_PARENT FOREIGN KEY (ID_INSTANCE_PARENT) REFERENCES {{P}}_INSTANCE (ID)
);

-- Une seule instance active par processus et par clé d'affaire (instances à instance unique) : index unique partiel.
CREATE UNIQUE INDEX IF NOT EXISTS {{P}}_UX_INST_UNIQUE ON {{P}}_INSTANCE (CLE_AFFAIRE, CLE_PROCESSUS)
    WHERE INSTANCE_UNIQUE = 1 AND STATUT IN ('EN_COURS', 'SUSPENDUE', 'EN_ERREUR');
CREATE INDEX IF NOT EXISTS {{P}}_IX_INST_STATUT ON {{P}}_INSTANCE (STATUT);
CREATE INDEX IF NOT EXISTS {{P}}_IX_INST_NOEUD ON {{P}}_INSTANCE (ID_DEFINITION, CODE_NOEUD_COURANT);
CREATE INDEX IF NOT EXISTS {{P}}_IX_INST_CLE ON {{P}}_INSTANCE (CLE_AFFAIRE, CLE_PROCESSUS);
CREATE INDEX IF NOT EXISTS {{P}}_IX_INST_PARENT ON {{P}}_INSTANCE (ID_INSTANCE_PARENT);

CREATE TABLE IF NOT EXISTS {{P}}_HIST_NOEUD (
    ID                  INTEGER NOT NULL,
    ID_INSTANCE         INTEGER NOT NULL,
    CODE_NOEUD          TEXT NOT NULL,
    TYPE_NOEUD          TEXT NOT NULL,
    DATE_ENTREE         TEXT NOT NULL,
    DATE_SORTIE         TEXT,
    RESULTAT            TEXT,
    PRIMARY KEY (ID),
    CONSTRAINT {{P}}_FK_HIST_INST FOREIGN KEY (ID_INSTANCE) REFERENCES {{P}}_INSTANCE (ID)
);

CREATE INDEX IF NOT EXISTS {{P}}_IX_HIST_INST ON {{P}}_HIST_NOEUD (ID_INSTANCE);

CREATE TABLE IF NOT EXISTS {{P}}_ATTENTE (
    ID                  INTEGER NOT NULL,
    ID_INSTANCE         INTEGER NOT NULL,
    CODE_NOEUD          TEXT NOT NULL,
    TYPE_DECLENCHEUR    TEXT NOT NULL,
    NOM_SORTIE          TEXT NOT NULL,
    DATE_ECHEANCE       TEXT,
    NOM_SIGNAL          TEXT,
    CLE_CORRELATION     TEXT,
    DATE_CREATION       TEXT NOT NULL,
    PRIMARY KEY (ID),
    CONSTRAINT {{P}}_FK_ATT_INST FOREIGN KEY (ID_INSTANCE) REFERENCES {{P}}_INSTANCE (ID)
);

CREATE INDEX IF NOT EXISTS {{P}}_IX_ATT_ECHEANCE ON {{P}}_ATTENTE (TYPE_DECLENCHEUR, DATE_ECHEANCE);
CREATE INDEX IF NOT EXISTS {{P}}_IX_ATT_SIGNAL ON {{P}}_ATTENTE (NOM_SIGNAL, CLE_CORRELATION);
CREATE INDEX IF NOT EXISTS {{P}}_IX_ATT_INST ON {{P}}_ATTENTE (ID_INSTANCE, CODE_NOEUD);

CREATE TABLE IF NOT EXISTS {{P}}_MIGRATION (
    ID                      INTEGER NOT NULL,
    ID_INSTANCE             INTEGER NOT NULL,
    ID_DEFINITION_SOURCE    INTEGER NOT NULL,
    ID_DEFINITION_CIBLE     INTEGER NOT NULL,
    MODE                    TEXT NOT NULL,
    DETAIL                  TEXT,
    UTILISATEUR             TEXT,
    DATE_MIGRATION          TEXT NOT NULL,
    PRIMARY KEY (ID),
    CONSTRAINT {{P}}_FK_MIG_INST FOREIGN KEY (ID_INSTANCE) REFERENCES {{P}}_INSTANCE (ID),
    CONSTRAINT {{P}}_FK_MIG_SOURCE FOREIGN KEY (ID_DEFINITION_SOURCE) REFERENCES {{P}}_DEFINITION (ID),
    CONSTRAINT {{P}}_FK_MIG_CIBLE FOREIGN KEY (ID_DEFINITION_CIBLE) REFERENCES {{P}}_DEFINITION (ID)
);

CREATE INDEX IF NOT EXISTS {{P}}_IX_MIG_INST ON {{P}}_MIGRATION (ID_INSTANCE);

-- Instances actives avec la clé et la version de leur définition, pour les requêtes SQL ad hoc.
CREATE VIEW IF NOT EXISTS {{P}}_V_INSTANCE_ACTIVE AS
SELECT i.ID, i.CLE_PROCESSUS, d.VERSION AS VERSION_DEFINITION, i.ID_DEFINITION, i.CLE_AFFAIRE, i.STATUT,
       i.CODE_NOEUD_COURANT, i.ID_INSTANCE_PARENT, i.MESSAGE_ERREUR, i.DATE_CREATION, i.DATE_MAJ
FROM {{P}}_INSTANCE i
JOIN {{P}}_DEFINITION d ON d.ID = i.ID_DEFINITION
WHERE i.STATUT IN ('EN_COURS', 'SUSPENDUE', 'EN_ERREUR');
