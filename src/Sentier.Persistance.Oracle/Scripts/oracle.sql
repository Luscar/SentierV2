-- Sentier : schéma Oracle (tables, séquences, index, vue).
-- Le jeton {{P}} est remplacé par le préfixe configuré (OptionsSentier.PrefixeTables).
-- Tous les noms d'objets tiennent en 30 caractères ; ils suivent les mnémoniques de BpmPlus.

CREATE SEQUENCE {{P}}_SEQ_DEFIN START WITH 1 INCREMENT BY 1 CACHE 20;
CREATE SEQUENCE {{P}}_SEQ_INSTC START WITH 1 INCREMENT BY 1 CACHE 20;
CREATE SEQUENCE {{P}}_SEQ_HIST_NOEUD START WITH 1 INCREMENT BY 1 CACHE 20;
CREATE SEQUENCE {{P}}_SEQ_ATTEN START WITH 1 INCREMENT BY 1 CACHE 20;
CREATE SEQUENCE {{P}}_SEQ_MIGRA START WITH 1 INCREMENT BY 1 CACHE 20;

CREATE TABLE {{P}}_DEFIN_PROCS (                    --DEFINITION_PROCESSUS
    NO_SEQ_DEFIN_PROCS  NUMBER(19)      NOT NULL,   --ID
    CLE                 VARCHAR2(100)   NOT NULL,   --CLE_PROCESSUS
    VERSI               NUMBER(10)      NOT NULL,   --VERSION
    NOM_DEFIN           VARCHAR2(200)   NOT NULL,   --NOM
    IND_INSTC_UNIQ      NUMBER(1)       NOT NULL,   --INSTANCE_UNIQUE
    IND_MIGRA_AUTO      NUMBER(1)       NOT NULL,   --MIGRATION_AUTO
    DEFIN_JSON          CLOB            NOT NULL,   --CONTENU
    EMPRE               VARCHAR2(64)    NOT NULL,   --EMPREINTE
    IND_ACTIV           NUMBER(1)       NOT NULL,   --EST_ACTIVE
    DH_CREA             TIMESTAMP       NOT NULL,   --DATE_CREATION
    CONSTRAINT PK_{{P}}_DEFIN PRIMARY KEY (NO_SEQ_DEFIN_PROCS)
);

CREATE UNIQUE INDEX UQ_{{P}}_DEFIN_CLE_VER ON {{P}}_DEFIN_PROCS (CLE, VERSI);
CREATE INDEX IDX_{{P}}_DEFIN_ACTIV ON {{P}}_DEFIN_PROCS (CLE, IND_ACTIV);

CREATE TABLE {{P}}_INSTC_PROCS (                    --INSTANCE_PROCESSUS
    NO_SEQ_INSTC_PROCS  NUMBER(19)      NOT NULL,   --ID
    NO_SEQ_DEFIN_PROCS  NUMBER(19)      NOT NULL,   --ID_DEFINITION
    CLE_DEFIN           VARCHAR2(100)   NOT NULL,   --CLE_PROCESSUS
    ID_INSTC_PARN       NUMBER(19),                 --ID_INSTANCE_PARENT
    ID_NOEUD_PARN       VARCHAR2(100),              --CODE_NOEUD_PARENT
    AGGRE_ID            NUMBER(19)      NOT NULL,   --CLE_AFFAIRE
    IND_INSTC_UNIQ      NUMBER(1)       NOT NULL,   --INSTANCE_UNIQUE
    STAT                VARCHAR2(20)    NOT NULL,   --STATUT
    ID_NOEUD_FIN        VARCHAR2(100),              --CODE_FIN
    ID_NOEUD_COUR       VARCHAR2(100)   NOT NULL,   --CODE_NOEUD_COURANT
    ID_TACH_EXTE        NUMBER(19),                 --ID_TACHE_COURANTE
    VAR_JSON            CLOB,                       --VARIABLES
    MESS_ERR            VARCHAR2(4000),             --MESSAGE_ERREUR
    DH_ERR              TIMESTAMP,                  --DATE_ERREUR
    VERSI               NUMBER(10)      NOT NULL,   --VERSION
    DH_CREA             TIMESTAMP       NOT NULL,   --DATE_CREATION
    DH_MODIF            TIMESTAMP       NOT NULL,   --DATE_MAJ
    DH_FIN              TIMESTAMP,                  --DATE_FIN
    CONSTRAINT PK_{{P}}_INSTC PRIMARY KEY (NO_SEQ_INSTC_PROCS),
    CONSTRAINT FK_{{P}}_INSTC_DEFIN FOREIGN KEY (NO_SEQ_DEFIN_PROCS) REFERENCES {{P}}_DEFIN_PROCS (NO_SEQ_DEFIN_PROCS),
    CONSTRAINT FK_{{P}}_INSTC_PARN FOREIGN KEY (ID_INSTC_PARN) REFERENCES {{P}}_INSTC_PROCS (NO_SEQ_INSTC_PROCS)
);

-- Une seule instance active par processus et par clé d'affaire (instances à instance unique) :
-- index unique fonctionnel, les lignes dont les deux expressions sont nulles ne sont pas indexées.
CREATE UNIQUE INDEX UQ_{{P}}_INSTC_UNIQ ON {{P}}_INSTC_PROCS (
    CASE WHEN IND_INSTC_UNIQ = 1 AND STAT IN ('EN_COURS', 'SUSPENDUE', 'EN_ERREUR') THEN AGGRE_ID END,
    CASE WHEN IND_INSTC_UNIQ = 1 AND STAT IN ('EN_COURS', 'SUSPENDUE', 'EN_ERREUR') THEN CLE_DEFIN END
);
CREATE INDEX IDX_{{P}}_INSTC_STAT ON {{P}}_INSTC_PROCS (STAT);
CREATE INDEX IDX_{{P}}_INSTC_NOEUD ON {{P}}_INSTC_PROCS (NO_SEQ_DEFIN_PROCS, ID_NOEUD_COUR);
CREATE INDEX IDX_{{P}}_INSTC_AGGID ON {{P}}_INSTC_PROCS (AGGRE_ID, CLE_DEFIN);
CREATE INDEX IDX_{{P}}_INSTC_PARN ON {{P}}_INSTC_PROCS (ID_INSTC_PARN);

CREATE TABLE {{P}}_HIST_NOEUD_PROCS (                   --HISTORIQUE_NOEUD
    NO_SEQ_HIST_NOEUD_PROCS NUMBER(19)      NOT NULL,   --ID
    NO_SEQ_INSTC_PROCS      NUMBER(19)      NOT NULL,   --ID_INSTANCE
    ID_NOEUD                VARCHAR2(100)   NOT NULL,   --CODE_NOEUD
    TYP_NOEUD               VARCHAR2(20)    NOT NULL,   --TYPE_NOEUD
    DH_ENTRE                TIMESTAMP       NOT NULL,   --DATE_ENTREE
    DH_SORTI                TIMESTAMP,                  --DATE_SORTIE
    RESUL                   VARCHAR2(400),              --RESULTAT
    CONSTRAINT PK_{{P}}_HIST PRIMARY KEY (NO_SEQ_HIST_NOEUD_PROCS),
    CONSTRAINT FK_{{P}}_HIST_INSTC FOREIGN KEY (NO_SEQ_INSTC_PROCS) REFERENCES {{P}}_INSTC_PROCS (NO_SEQ_INSTC_PROCS)
);

CREATE INDEX IDX_{{P}}_HIST_INSTC ON {{P}}_HIST_NOEUD_PROCS (NO_SEQ_INSTC_PROCS);

CREATE TABLE {{P}}_ATTEN_PROCS (                    --ATTENTE
    NO_SEQ_ATTEN_PROCS  NUMBER(19)      NOT NULL,   --ID
    NO_SEQ_INSTC_PROCS  NUMBER(19)      NOT NULL,   --ID_INSTANCE
    ID_NOEUD            VARCHAR2(100)   NOT NULL,   --CODE_NOEUD
    TYP_DECLN           VARCHAR2(10)    NOT NULL,   --TYPE_DECLENCHEUR
    NOM_SORTI           VARCHAR2(100)   NOT NULL,   --NOM_SORTIE
    DH_ECHEA            TIMESTAMP,                  --DATE_ECHEANCE
    NOM_SIGNL           VARCHAR2(100),              --NOM_SIGNAL
    CLE_CORRL           VARCHAR2(200),              --CLE_CORRELATION
    DH_CREA             TIMESTAMP       NOT NULL,   --DATE_CREATION
    CONSTRAINT PK_{{P}}_ATTEN PRIMARY KEY (NO_SEQ_ATTEN_PROCS),
    CONSTRAINT FK_{{P}}_ATTEN_INSTC FOREIGN KEY (NO_SEQ_INSTC_PROCS) REFERENCES {{P}}_INSTC_PROCS (NO_SEQ_INSTC_PROCS)
);

CREATE INDEX IDX_{{P}}_ATTEN_ECHEA ON {{P}}_ATTEN_PROCS (TYP_DECLN, DH_ECHEA);
CREATE INDEX IDX_{{P}}_ATTEN_SIGNL ON {{P}}_ATTEN_PROCS (NOM_SIGNL, CLE_CORRL);
CREATE INDEX IDX_{{P}}_ATTEN_INSTC ON {{P}}_ATTEN_PROCS (NO_SEQ_INSTC_PROCS, ID_NOEUD);

CREATE TABLE {{P}}_MIGRA_PROCS (                    --MIGRATION
    NO_SEQ_MIGRA_PROCS  NUMBER(19)      NOT NULL,   --ID
    NO_SEQ_INSTC_PROCS  NUMBER(19)      NOT NULL,   --ID_INSTANCE
    NO_SEQ_DEFIN_SOURC  NUMBER(19)      NOT NULL,   --ID_DEFINITION_SOURCE
    NO_SEQ_DEFIN_CIBLE  NUMBER(19)      NOT NULL,   --ID_DEFINITION_CIBLE
    MODE_MIGRA          VARCHAR2(10)    NOT NULL,   --MODE
    DETL                CLOB,                       --DETAIL
    LOGON_UTIL          VARCHAR2(200),              --UTILISATEUR
    DH_MIGRA            TIMESTAMP       NOT NULL,   --DATE_MIGRATION
    CONSTRAINT PK_{{P}}_MIGRA PRIMARY KEY (NO_SEQ_MIGRA_PROCS),
    CONSTRAINT FK_{{P}}_MIGRA_INSTC FOREIGN KEY (NO_SEQ_INSTC_PROCS) REFERENCES {{P}}_INSTC_PROCS (NO_SEQ_INSTC_PROCS),
    CONSTRAINT FK_{{P}}_MIGRA_SOURC FOREIGN KEY (NO_SEQ_DEFIN_SOURC) REFERENCES {{P}}_DEFIN_PROCS (NO_SEQ_DEFIN_PROCS),
    CONSTRAINT FK_{{P}}_MIGRA_CIBLE FOREIGN KEY (NO_SEQ_DEFIN_CIBLE) REFERENCES {{P}}_DEFIN_PROCS (NO_SEQ_DEFIN_PROCS)
);

CREATE INDEX IDX_{{P}}_MIGRA_INSTC ON {{P}}_MIGRA_PROCS (NO_SEQ_INSTC_PROCS);

-- Instances actives avec la clé et la version de leur définition, pour les requêtes SQL ad hoc.
CREATE OR REPLACE VIEW {{P}}_V_INSTC_ACTIV AS
SELECT i.NO_SEQ_INSTC_PROCS, i.CLE_DEFIN, d.VERSI AS VERSI_DEFIN, i.NO_SEQ_DEFIN_PROCS, i.AGGRE_ID, i.STAT,
       i.ID_NOEUD_COUR, i.ID_TACH_EXTE, i.ID_INSTC_PARN, i.MESS_ERR, i.DH_CREA, i.DH_MODIF
FROM {{P}}_INSTC_PROCS i
JOIN {{P}}_DEFIN_PROCS d ON d.NO_SEQ_DEFIN_PROCS = i.NO_SEQ_DEFIN_PROCS
WHERE i.STAT IN ('EN_COURS', 'SUSPENDUE', 'EN_ERREUR');
