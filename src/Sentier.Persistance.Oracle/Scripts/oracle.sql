-- Sentier : schéma Oracle (tables, séquences, index, vue).
-- Le jeton {{P}} est remplacé par le préfixe configuré (OptionsSentier.PrefixeTables).
-- Tous les noms d'objets tiennent en 30 caractères.

CREATE SEQUENCE {{P}}_SEQ_DEFINITION START WITH 1 INCREMENT BY 1 CACHE 20;
CREATE SEQUENCE {{P}}_SEQ_INSTANCE START WITH 1 INCREMENT BY 1 CACHE 20;
CREATE SEQUENCE {{P}}_SEQ_HIST_NOEUD START WITH 1 INCREMENT BY 1 CACHE 20;
CREATE SEQUENCE {{P}}_SEQ_ATTENTE START WITH 1 INCREMENT BY 1 CACHE 20;
CREATE SEQUENCE {{P}}_SEQ_MIGRATION START WITH 1 INCREMENT BY 1 CACHE 20;

CREATE TABLE {{P}}_DEFINITION (
    ID                  NUMBER(19)      NOT NULL,
    CLE_PROCESSUS       VARCHAR2(100)   NOT NULL,
    VERSION             NUMBER(10)      NOT NULL,
    NOM                 VARCHAR2(200)   NOT NULL,
    INSTANCE_UNIQUE     NUMBER(1)       NOT NULL,
    MIGRATION_AUTO      NUMBER(1)       NOT NULL,
    CONTENU             CLOB            NOT NULL,
    EMPREINTE           VARCHAR2(64)    NOT NULL,
    EST_ACTIVE          NUMBER(1)       NOT NULL,
    DATE_CREATION       TIMESTAMP       NOT NULL,
    CONSTRAINT {{P}}_PK_DEFINITION PRIMARY KEY (ID)
);

CREATE UNIQUE INDEX {{P}}_UX_DEF_VERSION ON {{P}}_DEFINITION (CLE_PROCESSUS, VERSION);
CREATE INDEX {{P}}_IX_DEF_ACTIVE ON {{P}}_DEFINITION (CLE_PROCESSUS, EST_ACTIVE);

CREATE TABLE {{P}}_INSTANCE (
    ID                  NUMBER(19)      NOT NULL,
    ID_DEFINITION       NUMBER(19)      NOT NULL,
    CLE_PROCESSUS       VARCHAR2(100)   NOT NULL,
    ID_INSTANCE_PARENT  NUMBER(19),
    CODE_NOEUD_PARENT   VARCHAR2(100),
    CLE_AFFAIRE         NUMBER(19)      NOT NULL,
    INSTANCE_UNIQUE     NUMBER(1)       NOT NULL,
    STATUT              VARCHAR2(20)    NOT NULL,
    CODE_FIN            VARCHAR2(100),
    CODE_NOEUD_COURANT  VARCHAR2(100)   NOT NULL,
    ID_TACHE_COURANTE   NUMBER(19),
    VARIABLES           CLOB,
    MESSAGE_ERREUR      VARCHAR2(4000),
    DATE_ERREUR         TIMESTAMP,
    VERSION             NUMBER(10)      NOT NULL,
    DATE_CREATION       TIMESTAMP       NOT NULL,
    DATE_MAJ            TIMESTAMP       NOT NULL,
    DATE_FIN            TIMESTAMP,
    CONSTRAINT {{P}}_PK_INSTANCE PRIMARY KEY (ID),
    CONSTRAINT {{P}}_FK_INST_DEF FOREIGN KEY (ID_DEFINITION) REFERENCES {{P}}_DEFINITION (ID),
    CONSTRAINT {{P}}_FK_INST_PARENT FOREIGN KEY (ID_INSTANCE_PARENT) REFERENCES {{P}}_INSTANCE (ID)
);

-- Une seule instance active par processus et par clé d'affaire (instances à instance unique) :
-- index unique fonctionnel, les lignes dont les deux expressions sont nulles ne sont pas indexées.
CREATE UNIQUE INDEX {{P}}_UX_INST_UNIQUE ON {{P}}_INSTANCE (
    CASE WHEN INSTANCE_UNIQUE = 1 AND STATUT IN ('EN_COURS', 'SUSPENDUE', 'EN_ERREUR') THEN CLE_AFFAIRE END,
    CASE WHEN INSTANCE_UNIQUE = 1 AND STATUT IN ('EN_COURS', 'SUSPENDUE', 'EN_ERREUR') THEN CLE_PROCESSUS END
);
CREATE INDEX {{P}}_IX_INST_STATUT ON {{P}}_INSTANCE (STATUT);
CREATE INDEX {{P}}_IX_INST_NOEUD ON {{P}}_INSTANCE (ID_DEFINITION, CODE_NOEUD_COURANT);
CREATE INDEX {{P}}_IX_INST_CLE ON {{P}}_INSTANCE (CLE_AFFAIRE, CLE_PROCESSUS);
CREATE INDEX {{P}}_IX_INST_PARENT ON {{P}}_INSTANCE (ID_INSTANCE_PARENT);

CREATE TABLE {{P}}_HIST_NOEUD (
    ID                  NUMBER(19)      NOT NULL,
    ID_INSTANCE         NUMBER(19)      NOT NULL,
    CODE_NOEUD          VARCHAR2(100)   NOT NULL,
    TYPE_NOEUD          VARCHAR2(20)    NOT NULL,
    DATE_ENTREE         TIMESTAMP       NOT NULL,
    DATE_SORTIE         TIMESTAMP,
    RESULTAT            VARCHAR2(400),
    CONSTRAINT {{P}}_PK_HIST_NOEUD PRIMARY KEY (ID),
    CONSTRAINT {{P}}_FK_HIST_INST FOREIGN KEY (ID_INSTANCE) REFERENCES {{P}}_INSTANCE (ID)
);

CREATE INDEX {{P}}_IX_HIST_INST ON {{P}}_HIST_NOEUD (ID_INSTANCE);

CREATE TABLE {{P}}_ATTENTE (
    ID                  NUMBER(19)      NOT NULL,
    ID_INSTANCE         NUMBER(19)      NOT NULL,
    CODE_NOEUD          VARCHAR2(100)   NOT NULL,
    TYPE_DECLENCHEUR    VARCHAR2(10)    NOT NULL,
    NOM_SORTIE          VARCHAR2(100)   NOT NULL,
    DATE_ECHEANCE       TIMESTAMP,
    NOM_SIGNAL          VARCHAR2(100),
    CLE_CORRELATION     VARCHAR2(200),
    DATE_CREATION       TIMESTAMP       NOT NULL,
    CONSTRAINT {{P}}_PK_ATTENTE PRIMARY KEY (ID),
    CONSTRAINT {{P}}_FK_ATT_INST FOREIGN KEY (ID_INSTANCE) REFERENCES {{P}}_INSTANCE (ID)
);

CREATE INDEX {{P}}_IX_ATT_ECHEANCE ON {{P}}_ATTENTE (TYPE_DECLENCHEUR, DATE_ECHEANCE);
CREATE INDEX {{P}}_IX_ATT_SIGNAL ON {{P}}_ATTENTE (NOM_SIGNAL, CLE_CORRELATION);
CREATE INDEX {{P}}_IX_ATT_INST ON {{P}}_ATTENTE (ID_INSTANCE, CODE_NOEUD);

CREATE TABLE {{P}}_MIGRATION (
    ID                      NUMBER(19)      NOT NULL,
    ID_INSTANCE             NUMBER(19)      NOT NULL,
    ID_DEFINITION_SOURCE    NUMBER(19)      NOT NULL,
    ID_DEFINITION_CIBLE     NUMBER(19)      NOT NULL,
    MODE                    VARCHAR2(10)    NOT NULL,
    DETAIL                  CLOB,
    UTILISATEUR             VARCHAR2(200),
    DATE_MIGRATION          TIMESTAMP       NOT NULL,
    CONSTRAINT {{P}}_PK_MIGRATION PRIMARY KEY (ID),
    CONSTRAINT {{P}}_FK_MIG_INST FOREIGN KEY (ID_INSTANCE) REFERENCES {{P}}_INSTANCE (ID),
    CONSTRAINT {{P}}_FK_MIG_SOURCE FOREIGN KEY (ID_DEFINITION_SOURCE) REFERENCES {{P}}_DEFINITION (ID),
    CONSTRAINT {{P}}_FK_MIG_CIBLE FOREIGN KEY (ID_DEFINITION_CIBLE) REFERENCES {{P}}_DEFINITION (ID)
);

CREATE INDEX {{P}}_IX_MIG_INST ON {{P}}_MIGRATION (ID_INSTANCE);

-- Instances actives avec la clé et la version de leur définition, pour les requêtes SQL ad hoc.
CREATE OR REPLACE VIEW {{P}}_V_INSTANCE_ACTIVE AS
SELECT i.ID, i.CLE_PROCESSUS, d.VERSION AS VERSION_DEFINITION, i.ID_DEFINITION, i.CLE_AFFAIRE, i.STATUT,
       i.CODE_NOEUD_COURANT, i.ID_TACHE_COURANTE, i.ID_INSTANCE_PARENT, i.MESSAGE_ERREUR, i.DATE_CREATION, i.DATE_MAJ
FROM {{P}}_INSTANCE i
JOIN {{P}}_DEFINITION d ON d.ID = i.ID_DEFINITION
WHERE i.STATUT IN ('EN_COURS', 'SUSPENDUE', 'EN_ERREUR');
